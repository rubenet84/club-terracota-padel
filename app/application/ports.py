from typing import Protocol

from app.application.schemas import JugadorCreate


class JugadorRepository(Protocol):
    """Contrato de persistencia que la aplicación necesita."""

    def listar(self) -> list[dict]: ...
    def listar_inactivos(self) -> list[dict]: ...
    def crear(self, datos: JugadorCreate) -> dict: ...
    def crear_lote(self, jugadores: list[JugadorCreate]) -> list[dict]: ...
    def actualizar(self, jugador_id: str, datos: JugadorCreate) -> dict: ...
    def desactivar(self, jugador_id: str) -> dict: ...
    def reactivar(self, jugador_id: str) -> dict: ...
    def eliminar(self, jugador_id: str) -> dict: ...
